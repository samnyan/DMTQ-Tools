using DMTQ.Tools.Core.Services.Pattern;
using FluentAssertions;

namespace DMTQ.Tools.Core.Tests.Services;

[TestClass]
public sealed class PtCipherTests
{
    [TestMethod]
    public void Decrypt_MatchesReferenceVectorFromLegacyTool()
    {
        var encrypted = new byte[]
        {
            0x50, 0x54, 0x46, 0x46, 0x01, 0x00, 0xC0, 0x00,
            0x00, 0x00, 0xF0, 0x42, 0x10, 0x00, 0x20, 0x00,
            0x00, 0x00, 0x00, 0x00, 0x20, 0x00, 0x00, 0x00,
            0x39, 0xFE, 0x53, 0x98, 0x80, 0xF5, 0x9F, 0x6A,
            0x17, 0x81, 0xE9, 0x03, 0x91, 0xA2, 0x21, 0x82
        };

        var expected = new byte[]
        {
            0x50, 0x54, 0x46, 0x46, 0x01, 0x00, 0xC0, 0x00,
            0x00, 0x00, 0xF0, 0x42, 0x10, 0x00, 0x20, 0x00,
            0x00, 0x00, 0x00, 0x00, 0x20, 0x00, 0x00, 0x00,
            0x01, 0x00, 0x00, 0x00, 0xDF, 0xF0, 0x01, 0x12,
            0x23, 0x34, 0x45, 0x56, 0x67, 0x78, 0x89, 0x9A
        };

        PtCipher.Decrypt(encrypted).Should().Equal(expected);
    }
}
